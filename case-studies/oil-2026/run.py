"""Run the oil case study end to end and write results/summary.json + results/summary.md.

    python run.py            # everything except the full variable search (~2-4 min)
    python run.py --search   # also run the 2,047-combination search (~25 min on a laptop)
    python run.py --step forecast   # one step: anomalies | forecast | holdout | search | posts | war
"""
import argparse
import json

import oilcase as oc

ap = argparse.ArgumentParser()
ap.add_argument("--search", action="store_true", help="run the full 1-3 variable search (slow)")
ap.add_argument("--step", default=None)
args = ap.parse_args()
want = lambda s: args.step in (None, s)

oc.RESULTS.mkdir(exist_ok=True)
p = oc.load_prices()
F = oc.anomaly_scores(p["brent"])
X = oc.monthly_features(p, F)
prev = oc.RESULTS / "summary.json"
out = json.loads(prev.read_text()) if (args.step and prev.exists()) else {}

if want("anomalies"):
    yr = (F.flag.groupby(F.index.year).mean() * 100).round(1)
    out["1_anomalies"] = {"share_of_days_flagged_top_years": yr.sort_values(ascending=False).head(6).to_dict(),
                          "after_flagged_vs_normal_days": oc.event_study(F)}
    print("1/6 anomalies done")

if want("forecast"):
    no_anom = ["Brent mom 1m", "Brent mom 12m", "Brent vs 5y avg", "Brent vol last month", "Brent-WTI spread"]
    out["2_forecast_walk_forward_2005_2026"] = {
        tgt: {name: oc.walk_forward(X, cols, tgt, "2005-01-31") for name, cols in
              [("volatility only", ["Brent vol last month"]), ("momentum+value+spread+volatility", no_anom),
               ("momentum+value+spread+anomaly", oc.FEATURES_DECK), ("core set", oc.FEATURES_CORE)]}
        for tgt in ["y_vol", "y_ret"]}
    print("2/6 forecasts done")

if want("holdout"):
    out["3_holdout_2026_volatility"] = {"with anomaly score": oc.holdout_2026(X, oc.FEATURES_CORE),
                                        "without anomaly score": oc.holdout_2026(X, ["Brent mom 1m", "Brent mom 12m", "Brent vs 5y avg", "Brent vol last month", "Brent-WTI spread"])}
    print("3/6 2026 holdout done")

if want("search"):
    k = 3 if args.search else 1
    out["4_variable_search"] = {f"{tgt} (max {k} vars)": oc.variable_search(X, tgt, max_k=k) for tgt in ["y_vol", "y_ret"]}
    print(f"4/6 variable search done (max {k} variables; use --search for the full 3-variable run)")

if want("posts"):
    P = oc.load_posts()
    out["5_trump_posts_event_study"] = oc.posts_event_study(p["brent"], P) if len(P) else "run fetch_data.py first to download the post archives"
    print("5/6 posts done")

if want("war"):
    out["6_war_attribution_2026"] = oc.war_attribution(p)
    print("6/6 war attribution done")

(oc.RESULTS / "summary.json").write_text(json.dumps(out, indent=1, default=str))
md = ["# Results", "", "Generated by `python run.py`. Out-of-sample R² is in % vs a historical-average forecast (0 = no better, negative = worse).", ""]
for k, v in out.items():
    md += [f"## {k}", "", "```", json.dumps(v, indent=1, default=str), "```", ""]
(oc.RESULTS / "summary.md").write_text("\n".join(md))
print("wrote results/summary.json and results/summary.md")
